function ModuleVisualizer({ moduleCode, isReal, previewUrl }) {
  const canvasRef = useRef(null)

  useEffect(() => {
    const canvas = canvasRef.current
    if (!canvas) return
    const ctx = canvas.getContext('2d')
    const width = canvas.width
    const height = canvas.height

    ctx.clearRect(0, 0, width, height)

    if (moduleCode === 'FFT') {
      // Draw 2D FFT Radial Frequency Distribution
      const cx = width / 2
      const cy = height / 2
      const maxR = Math.min(cx, cy) - 10

      // Radial circles
      for (let r = 20; r <= maxR; r += 20) {
        ctx.beginPath()
        ctx.arc(cx, cy, r, 0, Math.PI * 2)
        ctx.strokeStyle = 'rgba(0, 217, 255, 0.15)'
        ctx.stroke()
      }

      // Crosshairs
      ctx.beginPath()
      ctx.moveTo(cx, 0)
      ctx.lineTo(cx, height)
      ctx.moveTo(0, cy)
      ctx.lineTo(width, cy)
      ctx.strokeStyle = 'rgba(0, 217, 255, 0.25)'
      ctx.stroke()

      // High frequency peaks
      const pointCount = isReal ? 120 : 340
      for (let i = 0; i < pointCount; i++) {
        const angle = Math.random() * Math.PI * 2
        const dist = Math.pow(Math.random(), isReal ? 2.5 : 0.8) * maxR
        const px = cx + Math.cos(angle) * dist
        const py = cy + Math.sin(angle) * dist
        const ptColor = isReal ? 'rgba(16, 185, 129, 0.6)' : 'rgba(239, 68, 68, 0.7)'

        ctx.fillStyle = ptColor
        ctx.fillRect(px, py, isReal ? 1.5 : 2.5, isReal ? 1.5 : 2.5)
      }
    } else {
      // Default Cyber Waveform / Grid Simulation
      ctx.fillStyle = '#050816'
      ctx.fillRect(0, 0, width, height)

      // Cyber Grid
      ctx.strokeStyle = 'rgba(0, 217, 255, 0.1)'
      ctx.lineWidth = 1
      for (let x = 0; x < width; x += 20) {
        ctx.beginPath()
        ctx.moveTo(x, 0)
        ctx.lineTo(x, height)
        ctx.stroke()
      }
      for (let y = 0; y < height; y += 20) {
        ctx.beginPath()
        ctx.moveTo(0, y)
        ctx.lineTo(width, y)
        ctx.stroke()
      }

      // Signal Trace
      ctx.beginPath()
      ctx.moveTo(0, height / 2)
      for (let x = 0; x < width; x += 3) {
        const freq = isReal ? 0.05 : 0.12
        const noise = (Math.random() - 0.5) * (isReal ? 6 : 28)
        const y = height / 2 + Math.sin(x * freq) * (height * 0.28) + noise
        ctx.lineTo(x, y)
      }
      ctx.strokeStyle = isReal ? '#10b981' : '#ef4444'
      ctx.lineWidth = 2
      ctx.shadowColor = isReal ? '#10b981' : '#ef4444'
      ctx.shadowBlur = 10
      ctx.stroke()
    }
  }, [moduleCode, isReal])

  return (
    <div style={{
      width: '100%',
      height: '140px',
      background: '#040714',
      border: '1px solid rgba(0, 217, 255, 0.2)',
      borderRadius: '8px',
      overflow: 'hidden',
      position: 'relative'
    }}>
      <canvas ref={canvasRef} width={460} height={140} style={{ width: '100%', height: '100%', display: 'block' }} />
      <div style={{
        position: 'absolute',
        bottom: '6px',
        right: '10px',
        fontSize: '9.5px',
        fontFamily: 'monospace',
        color: '#64748b'
      }}>
        LIVE SIGNAL WAVEFORM TELEMETRY
      </div>
    </div>
  )
}
